"""Build the dependency-free filesystem/workspace host adapter."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent
SOURCES = ['workspace-controller.js', 'reader-adapter.js', 'workspace-panel.js', 'mount-reader.js']


def build(destination):
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    source = '\n\n'.join((ROOT/'web'/name).read_text() for name in SOURCES)
    temporary = destination.with_suffix(destination.suffix + '.tmp')
    temporary.write_text('/* Generated by filesystem-reader-integration/build.py; edit web/ sources. */\n' + source)
    temporary.replace(destination)
    return destination


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, default=ROOT/'dist'/'reader-link.js')
    args = parser.parse_args()
    print(build(args.output))
