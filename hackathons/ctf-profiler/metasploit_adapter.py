"""Optional Metasploit resource export and narrowly selected check adapter."""
from __future__ import annotations

import base64
import json
import re
from urllib.parse import urlsplit


def write_import_script(path, profile, nmap_data, workspace):
    """Embed encoded data, never target-controlled Ruby or console commands."""
    profile64 = base64.b64encode(json.dumps(profile, ensure_ascii=True).encode()).decode()
    scan64 = base64.b64encode(nmap_data or b"").decode()
    workspace64 = base64.b64encode(workspace.encode()).decode()
    script = """# Generated by CTF Profiler. Contains data import only.
# Portable: evidence is embedded; keep this file with your assessment records.
<ruby>
require 'json'
require 'base64'
if !framework.db.active
  print_error('Connect the Metasploit database, then load this resource again.')
else
  begin
    profile = JSON.parse(Base64.strict_decode64('__PROFILE__'))
    xml = Base64.strict_decode64('__SCAN__')
    name = Base64.strict_decode64('__WORKSPACE__')
    workspace = framework.db.find_workspace(name) || framework.db.add_workspace(name)
    framework.db.workspace = workspace
    unless xml.empty?
      framework.db.import(data: xml, workspace: name)
      print_status('Imported the validated single-target Nmap XML.')
    end
    framework.db.report_note(
      workspace: name, host: profile.fetch('target').fetch('ip'),
      type: 'ctf.device_profile', data: profile, update: :unique
    )
    if profile['classification']
      framework.db.report_note(
        workspace: name, host: profile.fetch('target').fetch('ip'),
        type: 'ctf.device_classification', data: profile['classification'], update: :unique
      )
    end
    profile.fetch('validated_vulnerabilities', []).each do |v|
      next unless v['status'] == 'reproduced'
      framework.db.report_vuln(
        workspace: name, host: profile.fetch('target').fetch('ip'),
        port: v['port'], proto: 'tcp', name: v['title'],
        info: JSON.generate(v), refs: []
      )
    end
    print_good('Attached the JSON device profile in workspace: ' + name)
    print_status('Review with hosts, services, and notes -t ctf.device_profile.')
  rescue StandardError => error
    print_error('Profile import failed: ' + error.message)
  end
end
</ruby>
"""
    script = script.replace("__PROFILE__", profile64).replace("__SCAN__", scan64)
    path.write_text(script.replace("__WORKSPACE__", workspace64), encoding="utf-8")


def metasploit_checks(base, port, profile, raw, execute, skip):
    # A finite mapping, never arbitrary module names supplied by the target.
    banners = " ".join(h.get("value", "") for o in profile["observations"] if o.get("tool") == "http" and o.get("port") == port for h in o.get("headers", []) if h.get("name", "").lower() == "server")
    if not re.search(r"Apache/2\.4\.(49|50)(?:\s|$)", banners):
        skip("metasploit_check", 5, "No observed product/version matches a reviewed check-module mapping", f"-{port}")
        return
    target = {"ip": profile["target"]["ip"], "port": port, "ssl": urlsplit(base).scheme == "https"}
    encoded = base64.b64encode(json.dumps(target).encode()).decode()
    report = raw / f"metasploit-check-{port}.json"
    encoded_path = base64.b64encode(str(report).encode()).decode()
    resource = raw / f"metasploit-check-{port}.rc"
    resource.write_text('''<ruby>
require 'json'
require 'base64'
t = JSON.parse(Base64.strict_decode64(''' + repr(encoded) + '''))
m = framework.exploits.create('multi/http/apache_normalize_path_rce')
m.datastore['RHOSTS'] = t['ip']
m.datastore['RPORT'] = t['port']
m.datastore['SSL'] = t['ssl']
m.datastore['VHOST'] = t['ip']
result = m.check
File.write(Base64.strict_decode64(''' + repr(encoded_path) + '''), JSON.generate({module: m.fullname, result: result.to_s, code: result.code.to_s, message: result.message}))
</ruby>
exit -y
''')
    execute(f"metasploit-check-{port}", "metasploit_check", 5, ["msfconsole", "-q", "-r", str(resource)],
            "Apache 2.4.49/2.4.50 banner makes the reviewed check eligible; no exploit/run command", report, format="json", port=port)
